import 'package:flutter/material.dart';

enum FieldType { text, password, number, date, choice, toggle, paragraph }

class FieldSpec {
  const FieldSpec(
    this.key,
    this.label, {
    this.type = FieldType.text,
    this.required = false,
    this.choices = const [],
    this.initial,
    this.hint,
  });
  final String key;
  final String label;
  final FieldType type;
  final bool required;
  final List<String> choices;
  final Object? initial;
  final String? hint;
}

class ModuleSpec {
  const ModuleSpec(
    this.key,
    this.title,
    this.path,
    this.icon,
    this.columns, {
    this.fields = const [],
    this.createLabel,
    this.editPath,
    this.adminOnly = false,
  });
  final String key, title, path;
  final IconData icon;
  final List<String> columns;
  final List<FieldSpec> fields;
  final String? createLabel, editPath;
  final bool adminOnly;
}

